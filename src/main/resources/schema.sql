CREATE TABLE IF NOT EXISTS schema_version (
    version INT PRIMARY KEY,
    applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL UNIQUE,
    password_hash VARCHAR(100),
    role VARCHAR(16),
    enabled BOOLEAN DEFAULT TRUE,
    session_version INT DEFAULT 0,
    created_by BIGINT,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS credential (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(64) NOT NULL UNIQUE,
    auth_type VARCHAR(24) NOT NULL,
    username VARCHAR(128),
    secret_cipher CLOB,
    last_tested_at TIMESTAMP,
    last_test_result VARCHAR(255),
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS project (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(128) NOT NULL UNIQUE,
    repo_url VARCHAR(512) NOT NULL UNIQUE,
    repo_type VARCHAR(16) DEFAULT 'FILE_PATH',
    credential_id BIGINT,
    base_branch VARCHAR(128) DEFAULT 'master',
    enabled BOOLEAN DEFAULT TRUE,
    deleted_at TIMESTAMP,
    delete_batch_id BIGINT DEFAULT 0 NOT NULL,
    last_activity_at TIMESTAMP,
    last_commit_author VARCHAR(128),
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS environment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(64) NOT NULL,
    env_key VARCHAR(64) NOT NULL,
    description VARCHAR(255),
    env_json CLOB,
    sort_no INT DEFAULT 0,
    enabled BOOLEAN DEFAULT TRUE,
    target_host VARCHAR(255),
    target_port INT,
    target_user VARCHAR(64),
    target_credential_id BIGINT,
    known_hosts_policy VARCHAR(16),
    deleted_at TIMESTAMP,
    delete_batch_id BIGINT DEFAULT 0 NOT NULL,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS trigger_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    environment_id BIGINT NOT NULL,
    enabled BOOLEAN DEFAULT TRUE,
    disabled_by_project BOOLEAN DEFAULT FALSE,
    overall_timeout_seconds INT DEFAULT 3600,
    delete_batch_id BIGINT DEFAULT 0 NOT NULL,
    deleted_at TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS trigger_step (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trigger_config_id BIGINT NOT NULL,
    step_index INT NOT NULL,
    name VARCHAR(64),
    step_type VARCHAR(16) NOT NULL,
    config_json CLOB,
    workdir VARCHAR(255) DEFAULT '.',
    env_json CLOB,
    timeout_seconds INT DEFAULT 600,
    poll_interval_seconds INT DEFAULT 2,
    enabled BOOLEAN DEFAULT TRUE,
    delete_batch_id BIGINT DEFAULT 0 NOT NULL,
    deleted_at TIMESTAMP,
    created_by VARCHAR(64),
    updated_by VARCHAR(64),
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT ck_poll_interval CHECK (poll_interval_seconds >= 0)
);

CREATE TABLE IF NOT EXISTS project_verify_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL UNIQUE,
    verify_type VARCHAR(16),
    enabled BOOLEAN DEFAULT TRUE,
    config_json CLOB,
    interval_seconds INT DEFAULT 2,
    request_timeout_seconds INT DEFAULT 5,
    timeout_seconds INT DEFAULT 300,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS auto_branch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    branch_name VARCHAR(255) NOT NULL,
    base_branch VARCHAR(128),
    source_branches VARCHAR(1024),
    suffix VARCHAR(16),
    last_commit_at TIMESTAMP,
    last_used_at TIMESTAMP,
    deleted BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP,
    CONSTRAINT uk_auto_branch UNIQUE (project_id, branch_name)
);

CREATE TABLE IF NOT EXISTS merge_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_type VARCHAR(16) NOT NULL,
    parent_task_id BIGINT,
    project_id BIGINT NOT NULL,
    environment_id BIGINT,
    overall_timeout_seconds INT,
    base_branch VARCHAR(128),
    source_branches VARCHAR(2048),
    auto_branch VARCHAR(255),
    base_commit_sha VARCHAR(64),
    auto_commit_sha VARCHAR(64),
    status VARCHAR(16) NOT NULL,
    stage VARCHAR(16),
    failed_stage VARCHAR(16),
    failed_step_index INT,
    step_total INT,
    step_current INT,
    callback_total_steps INT,
    callback_current_step INT,
    verify_attempts INT,
    last_verify_status VARCHAR(32),
    last_verify_message VARCHAR(1024),
    detail_url VARCHAR(2048),
    message VARCHAR(2048),
    callback_token VARCHAR(64),
    force_cancelled BOOLEAN DEFAULT FALSE,
    undo_of_task_id BIGINT,
    error_msg VARCHAR(2048),
    created_by BIGINT,
    created_by_name VARCHAR(64),
    merge_finished_at TIMESTAMP,
    created_at TIMESTAMP,
    started_at TIMESTAMP,
    finished_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS task_step (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    step_index INT NOT NULL,
    name VARCHAR(64),
    step_type VARCHAR(16),
    status VARCHAR(16),
    attempts INT DEFAULT 0,
    result_code INT,
    exit_code INT,
    last_status_code INT,
    last_body_excerpt CLOB,
    external_id VARCHAR(255),
    detail_url VARCHAR(2048),
    started_at TIMESTAMP,
    finished_at TIMESTAMP,
    log_size BIGINT DEFAULT 0,
    pid BIGINT
);

CREATE TABLE IF NOT EXISTS task_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL,
    step_index INT,
    step VARCHAR(128),
    level VARCHAR(8),
    content CLOB,
    created_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS project_lock (
    project_id BIGINT PRIMARY KEY,
    task_id BIGINT,
    acquired_by BIGINT,
    acquired_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(64),
    action VARCHAR(32),
    target_type VARCHAR(32),
    target_id VARCHAR(64),
    detail CLOB,
    ip VARCHAR(64),
    created_at TIMESTAMP
);

-- 唯一键包含 delete_batch_id，避免软删记录占用唯一键
CREATE UNIQUE INDEX IF NOT EXISTS uk_trigger_config_batch
    ON trigger_config (project_id, environment_id, delete_batch_id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_trigger_step_batch
    ON trigger_step (trigger_config_id, step_index, delete_batch_id);
-- 环境逻辑删除：唯一键包含 delete_batch_id，删除后同名/key 可重建
DROP INDEX IF EXISTS uk_environment_env_key;
CREATE UNIQUE INDEX IF NOT EXISTS uk_environment_name_batch
    ON environment (name, delete_batch_id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_environment_env_key_batch
    ON environment (env_key, delete_batch_id);
CREATE INDEX IF NOT EXISTS idx_environment_active ON environment (deleted_at);

CREATE INDEX IF NOT EXISTS idx_auto_branch_used ON auto_branch (project_id, last_used_at);
CREATE INDEX IF NOT EXISTS idx_task_project_branch ON merge_task (project_id, auto_branch);
CREATE INDEX IF NOT EXISTS idx_task_project_env ON merge_task (project_id, environment_id);
CREATE INDEX IF NOT EXISTS idx_task_status ON merge_task (status);
CREATE INDEX IF NOT EXISTS idx_task_created ON merge_task (created_at);
CREATE INDEX IF NOT EXISTS idx_task_parent ON merge_task (parent_task_id);
CREATE INDEX IF NOT EXISTS idx_task_step ON task_step (task_id, step_index);
CREATE INDEX IF NOT EXISTS idx_task_log ON task_log (task_id, step_index, id);
CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_log (created_at);
CREATE INDEX IF NOT EXISTS idx_audit_target ON audit_log (target_type, target_id);
